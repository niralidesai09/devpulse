import type { Metadata } from "next";
import Link from "next/link";
import { connection } from "next/server";
import { Badge, Card, EmptyState, ErrorPanel, PageHeader } from "@/components/ui";
import { listDecisions } from "@/lib/db/painPoints";
import { safeLoad } from "@/lib/db/safe";
import { fmtDateTime } from "@/lib/format";

export const metadata: Metadata = { title: "Decisions" };

const LABEL: Record<string, string> = { investigate: "Investigate", validate: "Validate with users", backlog: "Add to backlog", monitor: "Monitor", dismiss: "Dismiss" };
const TONE = { investigate: "accent", validate: "info", backlog: "good", monitor: "neutral", dismiss: "neutral" } as const;

export default async function DecisionsPage() {
  await connection();
  const loaded = await safeLoad(() => listDecisions());
  if (!loaded.ok) return <ErrorPanel title="Could not load decisions" error={loaded.error} />;
  const rows = loaded.data;
  return (
    <div className="space-y-6">
      <PageHeader title="Decision log" description="Product decisions recorded by the PM on pain points. Human decisions — never generated by AI. Newest first; earlier decisions are kept." />
      {rows.length === 0 ? (
        <EmptyState title="No decisions recorded yet">Open a pain point and record whether to investigate, validate, backlog, monitor or dismiss it.</EmptyState>
      ) : (
        <Card>
          <ul className="divide-y divide-border">
            {rows.map((d) => (
              <li key={d.id} className="px-4 py-3">
                <div className="flex flex-wrap items-center gap-2 text-sm">
                  <Badge tone={TONE[d.decision]}>{LABEL[d.decision]}</Badge>
                  {d.pain_point ? (
                    <Link href={`/pain-points/${d.pain_point.id}`} className="font-medium hover:underline">
                      {d.pain_point.title}
                    </Link>
                  ) : (
                    <span className="text-text-3">deleted pain point</span>
                  )}
                  <span className="text-xs text-text-3">
                    {fmtDateTime(d.created_at)} · {d.decided_by}
                    {d.report_id && (
                      <>
                        {" · "}
                        <Link href={`/reports/${d.report_id}`} className="hover:underline">
                          from report
                        </Link>
                      </>
                    )}
                  </span>
                </div>
                {d.rationale && <p className="mt-1 text-sm text-text-2">{d.rationale}</p>}
              </li>
            ))}
          </ul>
        </Card>
      )}
    </div>
  );
}
